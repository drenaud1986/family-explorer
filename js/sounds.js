const cache = {};
let enabled = true;
let unlocked = false;
export const setSoundEnabled = v => { enabled = !!v; };
export const soundEnabled = () => enabled;

function base(key) {
  if (!cache[key]) { const a = new Audio(SOUNDS[key].src); a.preload = 'auto'; cache[key] = a; }
  return cache[key];
}

/** Joue un son. options : volume (0-1), delay (ms). */
export function play(key, { volume = 0.8, delay = 0 } = {}) {
  if (!enabled || !SOUNDS[key]) return;
  setTimeout(() => {
    try {
      const a = base(key).cloneNode();
      a.volume = volume;
      const p = a.play();
      if (p) p.catch(() => {});
      const max = SOUNDS[key].max;
      if (max) setTimeout(() => fadeOut(a), max * 1000);
    } catch { /* pas de son : on continue sans */ }
  }, delay);
}

function fadeOut(a) {
  const t = setInterval(() => {
    a.volume = Math.max(0, a.volume - 0.08);
    if (a.volume <= 0.02) { a.pause(); clearInterval(t); }
  }, 40);
}

/** Précharge des sons (à appeler après un geste de l'utilisateur). */
export function preloadSounds(keys = Object.keys(SOUNDS)) {
  if (unlocked) return; unlocked = true;
  for (const k of keys) { try { base(k).load(); } catch { /* ignoré */ } }
}

export const soundURLs = () => Object.values(SOUNDS).map(s => s.src);
